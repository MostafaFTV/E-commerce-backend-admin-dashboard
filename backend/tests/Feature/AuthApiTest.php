    public function test_registration_otp_request_accepts_valid_data(): void
    {
        $this->fakeSmsAndCaptureOtp();

        $payload = $this->registrationPayload();

        $response = $this->postJson(
            '/api/auth/register/request-otp',
            $payload
        );

        $response
            ->assertOk()
            ->assertJsonPath(
                'message',
                'Verification code sent successfully.'
            )
            ->assertJsonPath(
                'expires_in',
                120
            )
            ->assertJsonPath(
                'retry_after',
                60
