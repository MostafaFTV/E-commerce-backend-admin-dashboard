    public function test_registration_is_completed_after_valid_otp(): void
    {
        $this->fakeSmsAndCaptureOtp();

        $registrationData = $this->registrationPayload();

        $this->postJson(
            '/api/auth/register/request-otp',
            $registrationData
        )->assertOk();

        $this->assertNotNull(
            $this->capturedOtp
        );

        $response = $this->postJson(
            '/api/auth/register/verify-otp',
            [
                'mobile' => $registrationData['phone'],
                'code' => $this->capturedOtp,
            ]
        );

        $response
            ->assertCreated()
            ->assertJsonPath(
                'message',
                'Registered successfully.'
            )
            ->assertJsonPath(
                'user.first_name',
                'John'
            )
            ->assertJsonPath(
                'user.last_name',
                'Doe'
            )
            ->assertJsonPath(
                'user.email',
                'john@example.com'
            )
            ->assertJsonPath(
                'user.phone',
                '09121111111'
            )
            ->assertJsonPath(
                'user.status',
                'active'
            )
            ->assertJsonPath(
                'user.roles.0.slug',
                'customer'
            )
            ->assertJsonStructure([
                'message',
                'user',
                'token',
            ]);

        $this->assertDatabaseHas(
            'users',
            [
                'email' => 'john@example.com',
                'phone' => '09121111111',
            ]
        );

        $user = User::where(
            'email',
            'john@example.com'
        )->firstOrFail();

        $this->assertNotNull(
            $user->phone_verified_at
        );

        $this->assertDatabaseCount(
            'personal_access_tokens',
            1
        );
    }

