    private function createCustomerRole(): Role
    {
        return Role::firstOrCreate(
            [
                'slug' => 'customer',
            ],
            [
                'name' => 'Customer',
                'description' => 'Customer role',
            ]
        );
    }

    private function createUser(array $attributes = []): User
    {
        $role = Role::where(
            'slug',
            'customer'
        )->firstOrFail();

        $user = User::create(array_merge([
            'first_name' => 'Test',
            'last_name' => 'Customer',
            'email' => 'customer@example.com',
            'phone' => '09120000000',
            'password' => 'password123',
            'status' => 'active',
        ], $attributes));

        $user->roles()->sync([
            $role->id,
        ]);

        return $user->fresh('roles');
    }

    private function authHeaders(string $token): array
    {
        return [
            'Authorization' => 'Bearer ' . $token,
            'Accept' => 'application/json',
        ];
    }

    private function registrationPayload(
        ?string $email = 'john@example.com',
        string $phone = '09121111111'
    ): array {
        $payload = [
            'first_name' => 'John',
            'last_name' => 'Doe',
            'phone' => $phone,
            'password' => 'password123',
            'password_confirmation' => 'password123',
        ];

        if ($email !== null) {
            $payload['email'] = $email;
        }

        return $payload;
    }

    /**
     * Replace SmsIrService with a fake implementation and capture
     * the OTP generated by OtpService.
     */
    private function fakeSmsAndCaptureOtp(): void
    {
        $this->app->bind(
            \App\Services\SmsIrService::class,
            function () {
                return Mockery::mock(
                    \App\Services\SmsIrService::class,
                    function ($mock) {
                        $mock
                            ->shouldReceive('sendVerify')
                            ->zeroOrMoreTimes()
                            ->withArgs(
                                function (
                                    string $mobile,
                                    string $code
                                ) {
                                    $this->capturedOtp = $code;

                                    return true;
                                }
                            )
                            ->andReturn([
                                'message_id' => 123456,
                                'cost' => 0,
                            ]);
                    }
                );
            }
        );
    }

    private ?string $capturedOtp = null;

